from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        ..., description="List of messages to be processed by the agent"
    )
    user_question: str = Field(..., description="The question asked by the user")
    curated_question: str = Field(..., description="Curated user Question")
    prompt_query_context: str = Field(
        ...,
        description="A detailed prompt with SQL DB context that will help agent to generate SQL Query.",
    )
    is_safe: Literal["Yes", "No"] = Field(
        ...,
        description="Indicated whether the query generated by the agent is safe or not",
    )
    comments: str = Field(
        ..., description="Comments regarding to the safety of the generated SQL query"
    )
    generated_sql_query: str = Field(
        ..., description="The SQL query generated by the agent"
    )
    sql_query_execution_result: str = Field(
        ..., description="The result of execution of the SQL query."
    )
    final_response: str = Field(
        ..., description="The final human readable response generated by the agent"
    )


class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(
        ..., description="Check whether this SQL query is safe to execute or not"
    )
    comments: str = Field(
        ...,
        description="Additional comments or feedback from the judge regarding the SQL query.",
    )


class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        ..., description="List of messages to be processed by the agent"
    )
